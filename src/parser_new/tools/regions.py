# Обратный индекс: название → код (строится один раз при импорте)
_NAME_TO_CODE: dict[str, str] = {}
for _code, _names in REGIONS.items():
    for _name in _names:
        _NAME_TO_CODE[_name.lower()] = _code


def get_region_code(region_name: str) -> str | None:
    """
    Возвращает числовой код региона по его названию.
    Нечувствителен к регистру и поддерживает разные варианты написания.

    Args:
        region_name: название региона в любом формате

    Returns:
        Строка с кодом (например "02") или None если не нашли
    """
    normalized = region_name.strip().lower()

    # Точное совпадение
    if normalized in _NAME_TO_CODE:
        return _NAME_TO_CODE[normalized]

    # Частичное совпадение — ищем вхождение
    for name, code in _NAME_TO_CODE.items():
        if normalized in name or name in normalized:
            return code

    return None


def get_region_name(code: str) -> str:
    """Возвращает первое (основное) название региона по коду."""
    names = REGIONS.get(code.zfill(2), [])
    return names[0].title() if names else f"Регион {code}"
