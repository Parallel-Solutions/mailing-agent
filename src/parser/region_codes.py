def get_region_code(region_name: str) -> str | None:
    """
    Возвращает двузначный код региона для Checko API.
    Поддерживает нечёткое сопоставление: сокращения, другой порядок слов,
    разные варианты написания.

    Args:
        region_name: название региона в любом виде

    Returns:
        Строка с кодом (например "01") или None если регион не найден
    """
    if not region_name:
        return None

    normalized = _normalize(region_name)

    # 1. Прямое совпадение в основном справочнике
    for official_name, code in _REGIONS.items():
        if _normalize(official_name) == normalized:
            return code

    # 2. Поиск по алиасам
    if normalized in _ALIASES:
        official_name = _ALIASES[normalized]
        return _REGIONS.get(official_name)

    # 3. Нечёткое совпадение — ищем по ключевому слову
    # Например "Свердловская обл." → ищем "свердловская" в справочнике
    key_word = _extract_key_word(normalized)
    if key_word:
        for official_name, code in _REGIONS.items():
            if key_word in _normalize(official_name):
                return code
        for alias, official_name in _ALIASES.items():
            if key_word in alias:
                return _REGIONS.get(official_name)

    return None


def get_all_regions() -> dict[str, str]:
    """Возвращает полный справочник: официальное название → код."""
    return dict(_REGIONS)


def _normalize(text: str) -> str:
    """Приводит название к нижнему регистру, убирает лишние символы."""
    text = text.lower().strip()
    # Убираем скобки с дублирующим названием типа "Адыгея (Адыгея)"
    text = re.sub(r"\s*\([^)]*\)", "", text)
    # Заменяем тире и дефисы на единый формат
    text = re.sub(r"\s*[—–-]\s*", " - ", text)
    # Убираем сокращения "обл.", "р-ка", "г."
    text = re.sub(r"\bобл\b\.?", "область", text)
    text = re.sub(r"\bр-ка\b", "республика", text)
    text = re.sub(r"\bг\.\s*", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text


def _extract_key_word(normalized: str) -> str:
    """
    Извлекает ключевое слово из названия региона.
    Например: "свердловская область" → "свердловская"
    """
    # Убираем общие слова
    stop_words = {
        "республика", "область", "край", "округ", "автономная",
        "автономный", "народная", "народный", "город", "федеральный"
    }
    words = normalized.split()
    key_words = [w for w in words if w not in stop_words and len(w) > 3]
    return key_words[0] if key_words else ""